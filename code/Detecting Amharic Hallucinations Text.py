from sklearn.metrics.pairwise import cosine_similarity
import numpy as np

def extract_kb_features(data):

    questions = kb_vectorizer.transform(
        data["question"].astype(str)
    )

    answers = kb_vectorizer.transform(
        data["answer"].astype(str)
    )

    distances, indices = kb_retriever.kneighbors(questions)

    features = []

    for i, idx in enumerate(indices):

        triple_vectors = kb_matrix[idx]

        # Answer similarity with retrieved triples
        answer_sim = cosine_similarity(
            answers[i], triple_vectors
        ).ravel()

        # Answer similarity with retrieved objects
        objects = knowledge_base.iloc[idx]["object"].tolist()
        object_vectors = kb_vectorizer.transform(objects)

        object_sim = cosine_similarity(
            answers[i], object_vectors
        ).ravel()

        # Convert cosine distances into similarities
        question_sim = 1 - distances[i]

        features.append([
            question_sim.max(),
            question_sim.mean(),
            answer_sim.max(),
            object_sim.max()
        ])

    return np.asarray(features, dtype=np.float32)


