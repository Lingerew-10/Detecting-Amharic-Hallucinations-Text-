# MODEL 4: HYBRID mBERT-BiLSTM + KNOWLEDGE BASE
# CELL 7: TRAIN HYBRID MODEL
# TASK: Train for 10 epochs and select the best validation model
# ============================================================

from copy import deepcopy
from sklearn.metrics import f1_score, accuracy_score

EPOCHS = 10

history_hybrid = {
    "train_loss": [],
    "val_loss": [],
    "train_accuracy": [],
    "val_accuracy": [],
    "val_macro_f1": []
}

best_val_f1 = -1.0
best_hybrid_state = None

for epoch in range(EPOCHS):

    hybrid_model.train()
    train_loss_total = 0
    train_true, train_pred = [], []

    for batch in train_loader_hybrid:
        input_ids = batch["input_ids"].to(device)
        attention_mask = batch["attention_mask"].to(device)
        kb_features = batch["kb_features"].to(device)
        labels = batch["labels"].to(device)

        optimizer.zero_grad()

        logits = hybrid_model(
            input_ids,
            attention_mask,
            kb_features
        )

        loss = criterion(logits, labels)
        loss.backward()

        torch.nn.utils.clip_grad_norm_(
            hybrid_model.parameters(), max_norm=1.0
        )

        optimizer.step()

        train_loss_total += loss.item()
        train_pred.extend(torch.argmax(logits, dim=1).cpu().numpy())
        train_true.extend(labels.cpu().numpy())

    train_loss = train_loss_total / len(train_loader_hybrid)
    train_accuracy = accuracy_score(train_true, train_pred)

    hybrid_model.eval()
    val_loss_total = 0
    val_true, val_pred = [], []

    with torch.no_grad():
        for batch in val_loader_hybrid:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            kb_features = batch["kb_features"].to(device)
            labels = batch["labels"].to(device)

            logits = hybrid_model(
                input_ids,
                attention_mask,
                kb_features
            )

            loss = criterion(logits, labels)
            val_loss_total += loss.item()

            val_pred.extend(
                torch.argmax(logits, dim=1).cpu().numpy()
            )
            val_true.extend(labels.cpu().numpy())

    val_loss = val_loss_total / len(val_loader_hybrid)
    val_accuracy = accuracy_score(val_true, val_pred)
    val_macro_f1 = f1_score(
        val_true, val_pred, average="macro", zero_division=0
    )

    history_hybrid["train_loss"].append(train_loss)
    history_hybrid["val_loss"].append(val_loss)
    history_hybrid["train_accuracy"].append(train_accuracy)
    history_hybrid["val_accuracy"].append(val_accuracy)
    history_hybrid["val_macro_f1"].append(val_macro_f1)

    if val_macro_f1 > best_val_f1:
        best_val_f1 = val_macro_f1
        best_hybrid_state = deepcopy(hybrid_model.state_dict())

    print(
        f"Epoch {epoch + 1}/{EPOCHS} | "
        f"Train Loss: {train_loss:.4f} | "
        f"Val Loss: {val_loss:.4f} | "
        f"Train Acc: {train_accuracy:.4f} | "
        f"Val Acc: {val_accuracy:.4f} | "
        f"Val Macro-F1: {val_macro_f1:.4f}"
    )

