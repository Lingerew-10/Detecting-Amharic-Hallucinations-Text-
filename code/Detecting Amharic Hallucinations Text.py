from torch.nn.utils.rnn import pack_padded_sequence

class HybridKBClassifier(nn.Module):
    def __init__(self, model_name, kb_feature_count=4):
        super().__init__()

        self.bert = AutoModel.from_pretrained(model_name)

        self.lstm = nn.LSTM(
            input_size=self.bert.config.hidden_size,
            hidden_size=128,
            num_layers=1,
            batch_first=True,
            bidirectional=True
        )

        self.dropout = nn.Dropout(0.3)

        self.classifier = nn.Linear(
            256 + kb_feature_count,
            2
        )

    def forward(self, input_ids, attention_mask, kb_features):
        outputs = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        sequence_output = outputs.last_hidden_state

        lengths = attention_mask.sum(dim=1).cpu()

        packed_sequence = pack_padded_sequence(
            sequence_output,
            lengths,
            batch_first=True,
            enforce_sorted=False
        )

        _, (hidden, _) = self.lstm(packed_sequence)

        text_features = torch.cat(
            (hidden[-2], hidden[-1]),
            dim=1
        )

        combined_features = torch.cat(
            (text_features, kb_features),
            dim=1
        )

        logits = self.classifier(
            self.dropout(combined_features)
        )

        return logits


